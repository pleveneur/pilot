// build-mcp-extension.js — Bundler esbuild pour l'extension MCP client de Pilot.
//
// L'agent pi ne supporte pas MCP nativement. Pour connecter Pilot (via une
// extension pi) à un serveur MCP tier, le SDK MCP (@modelcontextprotocol/sdk)
// est BUNDLÉ dans un fichier .ts auto-contenu :
//   - src-tauri/extensions/mcp-client.src.ts  (SOURCE, éditée à la main)
//   → src-tauri/extensions/pilot-mcp-client.ts (GÉNÉRÉ, embarqué via include_str!)
//
// Seules les imports pi (@earendil-works/pi-coding-agent) et typebox sont
// laissées EXTERNS (résolues par pi au runtime, comme les extensions actuelles).
// Tout le reste (le SDK MCP + ses dépendances npm) est inliné par esbuild en
// ESM, de sorte que le fichier généré est un module unique auto-contenu.
//
// Le fichier généré doit exister AVANT tout cargo build (include_str! à la
// compilation). Il est donc régénéré via `npm run build:mcp` :
//   - manuellement avant un cargo test --lib / cargo build,
//   - et automatiquement via beforeDevCommand / beforeBuildCommand (tauri.conf.json).
//
// Le fichier généré est ajouté au .gitignore (artefact de build).

import * as esbuild from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { writeFile } from "node:fs/promises";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const entryPoint = resolve(root, "src-tauri/extensions/mcp-client.src.ts");
const outfile = resolve(root, "src-tauri/extensions/pilot-mcp-client.ts");

const banner = [
  "// GENERATED FILE — DO NOT EDIT.",
  "// This file is auto-generated by `scripts/build-mcp-extension.js` (npm run build:mcp).",
  "// Source: src-tauri/extensions/mcp-client.src.ts",
  "// It bundles the MCP SDK (@modelcontextprotocol/sdk) so that pi can connect to a",
  "// POC MCP server without native MCP support. Only @earendil-works/pi-coding-agent",
  "// and typebox are left as externals, resolved by pi at runtime.",
].join("\n");

async function main() {
  const result = await esbuild.build({
    entryPoints: [entryPoint],
    outfile,
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node18",
    // Imports pi résolus par pi au runtime → non bundlées.
    external: ["@earendil-works/pi-coding-agent", "typebox"],
    banner: { js: banner },
    sourcemap: false,
    minify: false,
    logLevel: "info",
  });

  // esbuild.build() avec outfile écrit directement → aucun writeFiles nécessaire.
  // On vérifie que le fichier de sortie existe bien.
  try {
    const { stat } = await import("node:fs/promises");
    const st = await stat(outfile);
    console.log(
      `[build-mcp] OK → ${outfile} (${(st.size / 1024).toFixed(1)} Ko, ${
        "errors" in result && result.errors ? result.errors.length : 0
      } erreur(s))`
    );
  } catch (e) {
    console.error("[build-mcp] Sortie introuvable:", e.message);
    process.exit(1);
  }
}

main().catch((e) => {
  console.error("[build-mcp] Échec:", e);
  process.exit(1);
});
